// Draw n questions, unseen ones first. Twins may both appear, a few questions apart.
function drawConviction(diff, n, recentIds, rng = Math.random) {
  const shuffled = arr => {
    const a = [...arr];
    for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
    return a;
  };
  const recent = new Set(recentIds || []);
  // Group into units: a single question or a pair of twins
  const units = new Map();
  for (const pool of CONV_POOLS[diff]) {
    CONV_BANK[pool].forEach((row, i) => {
      const item = { id: `${pool}:${i}`, pool, text: row[0], answer: row[1], why: row[2] || '', twin: row[3] ? `${pool}:${row[3]}` : null };
      const key = item.twin || item.id;
      if (!units.has(key)) units.set(key, []);
      units.get(key).push(item);
    });
  }
  const fresh = u => !u.some(it => recent.has(it.id));
  const all = shuffled([...units.values()]);
  const ordered = [...all.filter(fresh), ...all.filter(u => !fresh(u))];
  const set = [];
  for (const u of ordered) {
    if (set.length >= n) break;
    if (u.length === 2 && rng() < 0.5 && set.length + 2 <= n) set.push(...u);
    else set.push(u[Math.floor(rng() * u.length)]);
  }
  // Shuffle, lift out each second twin, then re-insert it 3–8 questions from its
  // partner (inserting can only widen the gap of pairs already placed)
  const list = [];
  const later = [];
  const seen = new Map();
  for (const it of shuffled(set)) {
    if (it.twin && seen.has(it.twin)) later.push([seen.get(it.twin), it]);
    else { list.push(it); if (it.twin) seen.set(it.twin, it); }
  }
  for (const [first, second] of later) {
    const idx = list.indexOf(first);
    const gap = 3 + Math.floor(rng() * 6);
    if (idx + gap <= list.length) list.splice(idx + gap, 0, second);
    else list.splice(Math.max(0, idx + 1 - gap), 0, second);
  }
  return list;
}

